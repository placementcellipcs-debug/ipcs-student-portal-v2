-- GamePal persistence shared by authenticated student accounts.

CREATE TABLE IF NOT EXISTS gamepal_sessions (
  id CHAR(36) NOT NULL PRIMARY KEY,
  student_id CHAR(36) NULL,
  email VARCHAR(254) NOT NULL,
  roll_number VARCHAR(100) NULL,
  student_name VARCHAR(200) NULL,
  game_name VARCHAR(120) NOT NULL,
  category VARCHAR(80) NULL,
  score INT UNSIGNED NOT NULL DEFAULT 0,
  accuracy TINYINT UNSIGNED NOT NULL DEFAULT 0,
  time_seconds INT UNSIGNED NOT NULL DEFAULT 0,
  occurred_at DATETIME NULL,
  source_key VARCHAR(80) NOT NULL,
  source_tab VARCHAR(120) NOT NULL,
  source_record_key VARCHAR(180) NOT NULL,
  metadata JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_gamepal_session_source (source_key, source_tab, source_record_key),
  KEY ix_gamepal_sessions_email_time (email, occurred_at),
  KEY ix_gamepal_sessions_game (game_name, occurred_at),
  CONSTRAINT fk_gamepal_session_student FOREIGN KEY (student_id) REFERENCES student_profiles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gamepal_student_stats (
  id CHAR(36) NOT NULL PRIMARY KEY,
  student_id CHAR(36) NULL,
  email VARCHAR(254) NOT NULL,
  full_name VARCHAR(200) NULL,
  roll_number VARCHAR(100) NULL,
  branch_name VARCHAR(160) NULL,
  overall_brain_score INT UNSIGNED NOT NULL DEFAULT 0,
  memory_score INT UNSIGNED NOT NULL DEFAULT 0,
  attention_score INT UNSIGNED NOT NULL DEFAULT 0,
  language_score INT UNSIGNED NOT NULL DEFAULT 0,
  problem_solving_score INT UNSIGNED NOT NULL DEFAULT 0,
  math_score INT UNSIGNED NOT NULL DEFAULT 0,
  flexibility_score INT UNSIGNED NOT NULL DEFAULT 0,
  speed_score INT UNSIGNED NOT NULL DEFAULT 0,
  current_streak INT UNSIGNED NOT NULL DEFAULT 0,
  last_played_date DATE NULL,
  source_key VARCHAR(80) NOT NULL,
  source_tab VARCHAR(120) NOT NULL,
  source_record_key VARCHAR(180) NOT NULL,
  metadata JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_gamepal_stats_email (email),
  UNIQUE KEY uq_gamepal_stats_source (source_key, source_tab, source_record_key),
  KEY ix_gamepal_stats_score (overall_brain_score),
  CONSTRAINT fk_gamepal_stats_student FOREIGN KEY (student_id) REFERENCES student_profiles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gamepal_rooms (
  room_code VARCHAR(12) NOT NULL PRIMARY KEY,
  created_at DATETIME NULL,
  join_deadline DATETIME NULL,
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  game_id VARCHAR(64) NOT NULL,
  game_name VARCHAR(120) NOT NULL,
  creator_email VARCHAR(254) NOT NULL,
  creator_student_id CHAR(36) NULL,
  creator_name VARCHAR(200) NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'Waiting',
  max_players SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  source_key VARCHAR(80) NOT NULL,
  source_tab VARCHAR(120) NOT NULL,
  source_record_key VARCHAR(180) NOT NULL,
  metadata JSON NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_gamepal_room_source (source_key, source_tab, source_record_key),
  KEY ix_gamepal_room_creator (creator_email, created_at),
  KEY ix_gamepal_room_status (status, join_deadline),
  CONSTRAINT fk_gamepal_room_creator FOREIGN KEY (creator_student_id) REFERENCES student_profiles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gamepal_room_members (
  id CHAR(36) NOT NULL PRIMARY KEY,
  room_code VARCHAR(12) NOT NULL,
  email VARCHAR(254) NOT NULL,
  student_id CHAR(36) NULL,
  student_name VARCHAR(200) NULL,
  joined_at DATETIME NULL,
  score INT UNSIGNED NULL,
  accuracy TINYINT UNSIGNED NULL,
  source_key VARCHAR(80) NOT NULL,
  source_tab VARCHAR(120) NOT NULL,
  source_record_key VARCHAR(180) NOT NULL,
  metadata JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_gamepal_member_source (source_key, source_tab, source_record_key),
  KEY ix_gamepal_members_room (room_code, joined_at),
  KEY ix_gamepal_members_email (email, room_code),
  CONSTRAINT fk_gamepal_member_room FOREIGN KEY (room_code) REFERENCES gamepal_rooms(room_code) ON DELETE CASCADE,
  CONSTRAINT fk_gamepal_member_student FOREIGN KEY (student_id) REFERENCES student_profiles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gamepal_challenges (
  id CHAR(36) NOT NULL PRIMARY KEY,
  challenge_code VARCHAR(120) NOT NULL,
  created_at DATETIME NULL,
  updated_at DATETIME NULL,
  game_id VARCHAR(64) NOT NULL,
  game_name VARCHAR(120) NOT NULL,
  creator_email VARCHAR(254) NOT NULL,
  creator_student_id CHAR(36) NULL,
  creator_name VARCHAR(200) NULL,
  opponent_email VARCHAR(254) NOT NULL,
  opponent_student_id CHAR(36) NULL,
  opponent_name VARCHAR(200) NULL,
  creator_score INT UNSIGNED NULL,
  creator_accuracy TINYINT UNSIGNED NULL,
  opponent_score INT UNSIGNED NULL,
  opponent_accuracy TINYINT UNSIGNED NULL,
  status VARCHAR(60) NOT NULL DEFAULT 'Waiting for friend',
  source_key VARCHAR(80) NOT NULL,
  source_tab VARCHAR(120) NOT NULL,
  source_record_key VARCHAR(180) NOT NULL,
  metadata JSON NULL,
  refreshed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_gamepal_challenge_code (challenge_code),
  UNIQUE KEY uq_gamepal_challenge_source (source_key, source_tab, source_record_key),
  KEY ix_gamepal_challenge_creator (creator_email, created_at),
  KEY ix_gamepal_challenge_opponent (opponent_email, created_at),
  CONSTRAINT fk_gamepal_challenge_creator FOREIGN KEY (creator_student_id) REFERENCES student_profiles(id) ON DELETE SET NULL,
  CONSTRAINT fk_gamepal_challenge_opponent FOREIGN KEY (opponent_student_id) REFERENCES student_profiles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

