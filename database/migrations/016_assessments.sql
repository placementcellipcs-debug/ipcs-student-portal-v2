CREATE TABLE IF NOT EXISTS assessment_records (
  id CHAR(36) NOT NULL PRIMARY KEY,
  source_record_key VARCHAR(255) NOT NULL,
  source_key VARCHAR(120) NOT NULL,
  source_tab VARCHAR(160) NOT NULL,
  source_row_number INT UNSIGNED NULL,
  assessment_type VARCHAR(32) NOT NULL,
  record_type VARCHAR(24) NOT NULL,
  assessment_group VARCHAR(240) NULL,
  question_id VARCHAR(160) NULL,
  category VARCHAR(240) NULL,
  question_text MEDIUMTEXT NULL,
  option_a MEDIUMTEXT NULL,
  option_b MEDIUMTEXT NULL,
  option_c MEDIUMTEXT NULL,
  option_d MEDIUMTEXT NULL,
  answer_text MEDIUMTEXT NULL,
  explanation MEDIUMTEXT NULL,
  status_text VARCHAR(120) NULL,
  level_text VARCHAR(120) NULL,
  occurred_at_text VARCHAR(160) NULL,
  student_roll_number VARCHAR(160) NULL,
  student_name VARCHAR(240) NULL,
  student_email VARCHAR(254) NULL,
  student_branch VARCHAR(240) NULL,
  score_text VARCHAR(120) NULL,
  total_questions_text VARCHAR(120) NULL,
  percentage_text VARCHAR(120) NULL,
  time_taken_text VARCHAR(120) NULL,
  source_cells_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_assessment_source_record (source_record_key),
  UNIQUE KEY uq_assessment_source_row (source_key, source_tab, source_row_number),
  KEY ix_assessment_question_lookup (assessment_type, record_type, status_text, assessment_group(100)),
  KEY ix_assessment_result_lookup (assessment_type, record_type, student_email),
  KEY ix_assessment_result_time (assessment_type, record_type, source_row_number),
  CHECK (record_type IN ('question', 'result'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

