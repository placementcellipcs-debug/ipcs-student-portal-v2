CREATE TABLE IF NOT EXISTS student_diary_entries (
  id CHAR(36) NOT NULL PRIMARY KEY,
  source_record_key VARCHAR(255) NOT NULL,
  source_key VARCHAR(120) NOT NULL,
  source_tab VARCHAR(160) NOT NULL,
  source_row_number INT UNSIGNED NULL,
  user_id CHAR(36) NULL,
  student_profile_id CHAR(36) NULL,
  student_email VARCHAR(254) NULL,
  normalized_student_email VARCHAR(254) NULL,
  student_name VARCHAR(200) NULL,
  roll_number VARCHAR(100) NULL,
  branch_id CHAR(36) NULL,
  branch_name VARCHAR(160) NULL,
  course_id CHAR(36) NULL,
  course_name VARCHAR(200) NULL,
  source_timestamp VARCHAR(100) NULL,
  occurred_at DATETIME NULL,
  source_date VARCHAR(100) NULL,
  diary_date DATE NULL,
  record_type VARCHAR(40) NULL,
  status VARCHAR(80) NULL,
  topic TEXT NULL,
  syllabus_progress DECIMAL(5,2) NULL,
  remarks TEXT NULL,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  distance_meters DECIMAL(10,2) NULL,
  source_cells_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_student_diary_source_record (source_record_key),
  KEY ix_student_diary_student_date (normalized_student_email, diary_date, record_type),
  KEY ix_student_diary_profile_date (student_profile_id, diary_date),
  KEY ix_student_diary_branch_date (branch_id, diary_date),
  CONSTRAINT fk_student_diary_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_student_diary_profile FOREIGN KEY (student_profile_id) REFERENCES student_profiles(id) ON DELETE SET NULL,
  CONSTRAINT fk_student_diary_branch FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE SET NULL,
  CONSTRAINT fk_student_diary_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

