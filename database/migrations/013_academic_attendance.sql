CREATE TABLE IF NOT EXISTS academic_attendance_records (
  id CHAR(36) NOT NULL PRIMARY KEY,
  source_key VARCHAR(120) NOT NULL,
  source_tab VARCHAR(160) NOT NULL,
  source_row_number INT UNSIGNED NOT NULL,
  attendance_id VARCHAR(160) NULL,
  session_id VARCHAR(160) NULL,
  training_id VARCHAR(160) NULL,
  student_profile_id CHAR(36) NULL,
  source_student_id VARCHAR(160) NULL,
  student_name VARCHAR(200) NULL,
  course_id CHAR(36) NULL,
  main_course VARCHAR(200) NULL,
  sub_course VARCHAR(200) NULL,
  branch_id CHAR(36) NULL,
  branch_name VARCHAR(160) NULL,
  attendance_date DATE NULL,
  attendance_status VARCHAR(80) NULL,
  marking_method VARCHAR(120) NULL,
  verified VARCHAR(40) NULL,
  verified_by VARCHAR(200) NULL,
  remarks TEXT NULL,
  metadata JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_academic_attendance_source_row (source_key, source_tab, source_row_number),
  KEY ix_academic_attendance_student_date (student_profile_id, attendance_date),
  KEY ix_academic_attendance_branch_course_date (branch_id, course_id, attendance_date),
  KEY ix_academic_attendance_source_student (source_student_id),
  CONSTRAINT fk_academic_attendance_student FOREIGN KEY (student_profile_id) REFERENCES student_profiles(id) ON DELETE SET NULL,
  CONSTRAINT fk_academic_attendance_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE SET NULL,
  CONSTRAINT fk_academic_attendance_branch FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

